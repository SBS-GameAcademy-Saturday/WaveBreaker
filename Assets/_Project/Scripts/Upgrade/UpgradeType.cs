public enum UpgradeType
{
    BladeCount,     // 칼 한 자루 추가
    BladeSpeed,     // 칼 회전 속도 상승
    BladeDamage,    // 칼 피해 상승
    FireRate,       // 총 연사 상승
    GunDamage,      // 총알 피해 상승
    Pierce,         // 총알 관통 +1
    MoveSpeed,      // 이동 속도 상승
    MaxHealth       // 최대 체력 상승 (그만큼 회복도 된다)
}
