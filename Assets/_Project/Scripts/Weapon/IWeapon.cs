//    "시작할 때 이 무기를 준다" 를 하려면 총·칼·검기를 **같은 것으로 취급**해야 한다.
//    셋의 공통점은 "가지고 있나(Owned)" 와 "얻는다(Acquire)" 두 가지뿐이다.
